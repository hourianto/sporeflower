pub(crate) fn sources(program: &Program<'_>) -> Vec<MappingSource> {
    PACKS
        .iter()
        .filter(|(_, owners, _)| {
            owners
                .iter()
                .all(|owner| program.id(owner).is_some_and(|id| !program.is_own(id)))
        })
        .map(|(name, _, source)| MappingSource {
            path: format!("builtin-mappings/{name}"),
            source: (*source).into(),
            builtin: true,
        })
        .collect()
}
